DECIMAL = ","   # set per locale before each render


def main():
    global DECIMAL

    imgs = load_manifest()
    logo_mark = read("assets/icons/logo-mark.svg")
    logo_inner = logo_mark.split(">", 1)[1].rsplit("</svg>", 1)[0]

    env = Environment(
        loader=FileSystemLoader(rel("templates")),
        undefined=StrictUndefined,
        trim_blocks=False,
        lstrip_blocks=True,
        autoescape=True,
    )
    tpl = env.get_template("page.html.j2")

    css_raw, css_min = build_css()
    js_raw, js_min = build_js()

    srcset_fn = make_srcset(imgs)
    chart_html = chart_builder(imgs)
    sizes = {}

    for lang, out in LOCALES:
        with open(rel("content", f"{lang}.json"), encoding="utf-8") as fh:
            c = json.load(fh)

        DECIMAL = "," if lang == "uk" else "."
        prefix = c["dir_prefix"]
        canonical = BASE if lang == "uk" else BASE + "en/"
        thousands = " " if lang == "uk" else ","

        def fmt_num(n, _t=thousands):
            return f"{n:,}".replace(",", _t)

        def srcset(name, ext, _p=prefix):
            return srcset_fn(name, ext).replace("{P}", _p)

        html = tpl.render(
            c=c,
            imgs=imgs,
            base=BASE,
            canonical=canonical,
            year=BUILD_YEAR,
            logo_mark=Markup(logo_inner),
            srcset=srcset,
            chart_html=chart_html,
            fan=fan_transforms(len(c["hero"]["cards"])),
            orbit=ORBIT,
            geo_imgs=GEO_IMGS,
            fmt_num=fmt_num,
            ha="га" if lang == "uk" else "ha",
            tel="+" + re.sub(r"\D", "", c["contact"]["phone"]),
            jsonld=Markup(build_jsonld(c, lang, canonical)),
        )

        # collapse the blank lines Jinja's block tags leave behind
        html = re.sub(r"\n{3,}", "\n\n", html)
        sizes[out] = write(out, html)

    build_side_files(json.load(open(rel("content", "uk.json"), encoding="utf-8")))
    nf = build_404(json.load(open(rel("content", "uk.json"), encoding="utf-8")))

    print("BUILD OK")
    print(f"  css      {css_raw/1024:6.1f} KB -> {css_min/1024:6.1f} KB min")
    print(f"  js       {js_raw/1024:6.1f} KB -> {js_min/1024:6.1f} KB min")
    for out, n in sizes.items():
        print(f"  {out:16s} {n/1024:6.1f} KB")
    print(f"  404.html         {nf/1024:6.1f} KB")
    return 0


if __name__ == "__main__":
    sys.exit(main())
