def load_manifest():
    with open(rel("assets/img/manifest.json"), encoding="utf-8") as fh:
        return json.load(fh)


def make_srcset(imgs):
    def srcset(name, ext):
        m = imgs[name]
        return ", ".join(
            f"{{P}}assets/img/{name}-{w}.{ext} {w}w" for w in m["widths"]
        )
    return srcset


def fan_transforms(n):
    """Per-card 3D placement for the hero fan.

    Computed here rather than in CSS so the arc stays exact for any card count
    and the stylesheet needs no abs()/trig support.
    """
    mid = (n - 1) / 2
    out = []
    for i in range(n):
        a = i - mid
        d = abs(a)
        out.append({
            "ry": round(-a * 8.5, 2),
            "rz": round(a * 1.35, 2),
            "ty": round(d * d * 4.2 + d * 5.0, 1),
            "tz": round(-d * 26, 1),
            "sc": round(1 - d * 0.019, 3),
            "z": n - int(d * 2),
        })
    return out


def chart_builder(imgs):
    """Return a callable the template uses for both chart sizes.

    Bars are scaled between the series minimum and maximum rather than from
    zero: with a 0-baseline a 4.9 -> 6.4 t/ha spread is visually flat. Every
    exact value is printed above its bar, so nothing is hidden by the choice.
    """
    def chart_html(series, big=False):
        vals = [s["v"] for s in series]
        lo, hi = min(vals), max(vals)
        span = (hi - lo) or 1
        cols, years = [], []
        for i, s in enumerate(series):
            pct = 42 + 58 * (s["v"] - lo) / span
            cls = "chart__col"
            if s["v"] == hi:
                cls += " chart__col--peak"
            elif s["v"] == lo:
                cls += " chart__col--dip"
            label = f'{s["v"]:.1f}'.replace(".", DECIMAL)
            cols.append(
                f'<div class="{cls}" style="--h:{pct:.1f}%;--i:{i}">'
                f'<span class="chart__val">{label}</span>'
                f'<span class="chart__fill"></span></div>'
            )
            years.append(f"<span>{s['year']}</span>")
        return Markup(
            '<div class="chart"><div class="chart__plot">'
            + "".join(cols)
            + '</div><div class="chart__years">'
            + "".join(years)
            + "</div></div>"
        )
    return chart_html


