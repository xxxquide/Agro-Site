"""Build the static site: two locales from one template, one minified CSS/JS bundle.

Everything the browser downloads is produced here and committed, so GitHub Pages
can serve the repository directly with no CI step and no build on the server.

  python3 tools/build_site.py

Outputs: index.html, en/index.html, 404.html, assets/css/main.css,
assets/js/app.js, assets/img/og-*.jpg, robots.txt, sitemap.xml,
site.webmanifest, .nojekyll
"""
