# which cluster photo backs each parcel in the geography plan
GEO_IMGS = ["ops-elevator", "crop-wheat", "crop-corn"]

# orbit arms: irregular angles so the four pills never line up
ORBIT = [
    {"a": 22, "r": "30%", "d": 54},
    {"a": 112, "r": "37%", "d": 64},
    {"a": 203, "r": "31%", "d": 48},
    {"a": 292, "r": "38%", "d": 59},
]


def rel(*parts):
    return os.path.join(ROOT, *parts)


def read(path):
    with open(rel(path), encoding="utf-8") as fh:
        return fh.read()


def write(path, text):
    full = rel(path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, "w", encoding="utf-8") as fh:
        fh.write(text)
    return len(text.encode("utf-8"))


# ---------------------------------------------------------------------------
# assets: one CSS file, one JS file
# ---------------------------------------------------------------------------

def build_css():
    raw = "\n".join(read(p) for p in CSS_PARTS)
    mini = rcssmin.cssmin(raw)
    n = write("assets/css/main.css", mini)
    return len(raw.encode()), n


def build_js():
    raw = read("src/js/app.js")
    mini = rjsmin.jsmin(raw)
    n = write("assets/js/app.js", mini)
    return len(raw.encode()), n


