def main():
    path = os.path.join(ROOT, "content", "uk.json")
    with open(path, encoding="utf-8") as fh:
        data = json.load(fh)

    for key, value in NEW.items():
        data[key] = value

    with open(path, "w", encoding="utf-8") as fh:
        json.dump(data, fh, ensure_ascii=False, indent=2)
        fh.write("\n")

    print(f"uk.json: {len(NEW)} blocks written -> {len(data)} top-level keys")
    for k in NEW:
        v = data[k]
        n = len(v.get("items", v.get("posts", v.get("row_a", [])))) if isinstance(v, dict) else 0
        print(f"  {k:16s} {n if n else ''}")


if __name__ == "__main__":
    main()
