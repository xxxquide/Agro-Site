#!/usr/bin/env python3
"""Emit the same report as Markdown, from the same data the PDF is built from.

Two formats, one source: a divergence between them would be worse than having
only one. Markdown is what belongs in the repository — it diffs, it reviews, and
GitHub renders it. The PDF is the same content laid out for reading and printing.
"""
import importlib.util
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location("bp", os.path.join(HERE, "build_pdf.py"))
bp = importlib.util.module_from_spec(spec)
spec.loader.exec_module(bp)


def de_html(s):
    s = s.replace("<code>", "`").replace("</code>", "`")
    s = s.replace("&lt;", "<").replace("&gt;", ">").replace("&amp;", "&")
    s = s.replace("&nbsp;", " ")
    return re.sub(r"<[^>]+>", "", s)


def main():
    L = []
    w = L.append

    w("# ТОВ «ЦЕНТРАГРО ПЛЮС» — отчёт о работе\n")
    w("Доступность, время блокировки, страницы культур, юридические страницы и SEO. "
      "Пять фаз, каждая измерена относительно эталона, снятого до первой правки.\n")
    w(f"- **Ветка:** `feat/a11y-perf-crops-seo`, отведена от `feat/reference-grade-redesign`")
    w(f"- **Коммитов локально:** {len(bp.COMMITS)}, по одному на фазу")
    w(f"- **Диффстат:** {bp.DIFFSTAT}")
    w("- **Дата:** 7 августа 2026\n")

    w("> **Главный принцип приёмки.** Существующие страницы обязаны остаться пиксель "
      "в пиксель. Порог — доля пикселей с отличием более 30 по любому каналу ≤ 0,05 %. "
      "Единственное намеренное визуальное изменение за весь проход — фаза B3 (контраст), "
      "она вынесена в отдельный коммит и откатывается независимо. Пересборка после "
      "коммита даёт **0 изменённых файлов**: артефакты в репозитории в точности "
      "соответствуют источникам.\n")

    w("## Коммиты\n")
    for h, s in bp.COMMITS:
        w(f"- `{h}` {s}")
    w("")

    w("## 1. Метрики\n")
    w("| Метрика | До | После | Цель | Статус |")
    w("|---|---|---|---|---|")
    for n, b, a, t, ok in bp.METRICS:
        mark = "✅" if ok else "⚠️ см. §6"
        w(f"| {de_html(n)} | {de_html(b)} | **{de_html(a)}** | {de_html(t)} | {mark} |")
    w("")

    w("## 2. Попиксельное сравнение\n")
    w("Матрица — 39 снимков, после фазы C — 54 (добавились страницы культур): главная "
      "V1/V2/V3 × 1440×900 и 412×823 × позиции 0/2000/4200/7600, услуги V1/V2/V3, "
      "статья, контакты, о нас, блог, профиль, EN-главная, страница культуры V1/V2/V3.\n")
    w("| Фаза | Худший снимок | Сверх порога | Вердикт |")
    w("|---|---|---|---|")
    for n, ws, o, v in bp.PIXELS:
        w(f"| {n} | {ws} | {o} | {'**намеренно**' if v == 'намеренно' else v} |")
    w("")
    w("> **Шум измерен отдельно.** Два прогона одной и той же сборки расходятся до "
      "0,0102 % (до 0,036 % на снимках главной в позиции 2000 — там линия триггера "
      "проходит ровно по столбчатой диаграмме). Чтобы получить такой шум, харнесс "
      "пришлось починить: позиция скролла набирается колёсиком, а не `scrollTo` "
      "(Lenis держит свою цель и перезаписывает программный скролл), и перед кадром "
      "сбрасываются бесконечные анимации и снимается `will-change` — из-за него слова "
      "заголовков переключались между grayscale- и subpixel-сглаживанием. Без этих двух "
      "правок одна и та же сборка расходилась с собой на 1,36 %.\n")

    w("## 3. Единственное намеренное визуальное изменение — фаза B3\n")
    w("`--grey-300` и `--lime-lo` — цвета для тёмных поверхностей, и на белом давали "
      "1,69:1 и 1,37:1 против требуемых 4,5:1. Оба исходных токена не тронуты; добавлены "
      "два для текста на светлом. Менялась только светлота, и только до прохождения "
      "порога. Проверял и на `--grey-100`, не только на белом: серая панель на контактах "
      "стоит примерно 0,4 пункта отношения, и «граничный» #767676 проходит на белом "
      "(4,54:1) и не проходит на #f4f5f1 (4,14:1).\n")
    w("Фрагменты до/после — в PDF-версии отчёта, стр. 3.\n")

    w("## 4. Страницы культур\n")
    w("Семь культур делили одну страницу `/services/`. Теперь у каждой своя: "
      "`/services/<slug>/`, 42 новые страницы, 14 индексируемых. `crop.html.j2` не "
      "упоминает `V` и не вводит ни одного нового класса — только те, что "
      "`07-variants.css` уже знает. Поэтому вариации оформили страницу самостоятельно: "
      "на одной и той же странице расходится от 4 % до 59 % пикселей в зависимости от "
      "глубины скролла. Скриншоты трёх вариаций и пары «статья / культура» — в PDF, стр. 4–5.\n")

    w("## 5. Новые CSS-классы и токены\n")
    w("Один новый класс за весь проход. Остальное — новые правила для существующих классов.\n")
    w("| Селектор / токен | Тип | Обоснование |")
    w("|---|---|---|")
    for s, k, why in bp.CSS_ROWS:
        w(f"| `{s}` | {k} | {de_html(why)} |")
    w("")

    w("## 6. Что не сделано и почему\n")
    for t, d in bp.NOT_DONE:
        w(f"### {t}\n\n{de_html(d)}\n")

    w("## 7. Требует решения владельца\n")
    for i, (t, d) in enumerate(bp.DECISIONS, 1):
        w(f"{i}. **{t}.** {de_html(d)}")
    w("")
    w("Полный список — в `docs/CONTENT-GUIDE.md`, раздел «Что надо добавить до запуска», "
      "где к каждому факту указан файл и ключ, а также перекрёстные проверки, которые "
      "должны сходиться: земельный банк = сумма семи площадей; полоса ёмкости нарисована "
      "как 46 000 / 58 000.\n")

    w("## 8. Проверки: что и чем измерено\n")
    w("| Инструмент | Результат |")
    w("|---|---|")
    for t, r in bp.TOOLS:
        w(f"| `{t}` | {de_html(r)} |")
    w("")

    w("## 9. Побочные находки\n")
    for t, d in bp.FINDINGS:
        w(f"### {t}\n\n{de_html(d)}\n")

    w("## 10. Документация\n")
    w("- **README.md** — таблица весов перемерена: обещала 97,0 КБ для `index.html` при "
      "фактических 155,2 КБ (расхождение 59 %, снималось восемью коммитами ранее). "
      "Обновлены счётчики страниц и URL. Добавлены разделы «Доступность: контракт "
      "reveal-слоя» и «Страницы культур».")
    w("- **docs/ARCHITECTURE.md** — новый. Тройной цикл генерации, как вариации работают "
      "через класс на `body`, почему шаблоны detail-страниц не знают про `V`, и обе "
      "половины контракта моушн-слоя.")
    w("- **docs/CONTENT-GUIDE.md** — новый. Карта «факт о компании → файл и ключ», "
      "перекрёстные проверки, девять пунктов «добавить до запуска», известные ограничения.")
    w("- **CHANGELOG.md** — одна запись на проход, по фазам.\n")

    out = os.path.join(HERE, "REPORT.md")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(L))
    print(f"MD -> {out}  ({os.path.getsize(out)/1024:.0f} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
